create or replace function private.is_master_admin()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select coalesce((select p.global_role = 'master_admin' and p.is_active from public.profiles p where p.id = (select auth.uid())), false)
$$;

create or replace function private.is_company_member(target_company uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select private.is_master_admin() or exists (
    select 1 from public.company_members m
    where m.company_id = target_company and m.user_id = (select auth.uid()) and m.is_active
  )
$$;

create or replace function private.has_company_role(target_company uuid, allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select private.is_master_admin() or exists (
    select 1 from public.company_members m
    where m.company_id = target_company and m.user_id = (select auth.uid()) and m.is_active and m.role = any(allowed_roles)
  )
$$;

revoke all on function private.is_master_admin() from public, anon;
revoke all on function private.is_company_member(uuid) from public, anon;
revoke all on function private.has_company_role(uuid,text[]) from public, anon;
grant execute on function private.is_master_admin() to authenticated;
grant execute on function private.is_company_member(uuid) to authenticated;
grant execute on function private.has_company_role(uuid,text[]) to authenticated;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  insert into public.profiles (id,email,name,global_role)
  values (
    new.id,
    coalesce(new.email,''),
    coalesce(new.raw_user_meta_data ->> 'name', split_part(coalesce(new.email,'Usuário'),'@',1)),
    case when lower(coalesce(new.email,'')) = 'ana@verdecrm.local' then 'master_admin' else 'user' end
  )
  on conflict (id) do update set email=excluded.email, name=excluded.name, updated_at=now();
  return new;
end
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert or update of email on auth.users
for each row execute function private.handle_new_user();

